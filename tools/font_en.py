"""font_en.py: the English font and text encoder (phase 5 engine, docs/re/english.md).

The game draws text as vertical columns of 12 px glyph cells (one OBJ per cell, columns right to left). English is
drawn rotated 90 degrees clockwise: a column is one line read top to bottom, and the columns read right to left,
which is top to bottom once the player tilts the head (or the GBA) to the right. Each 12 px cell holds two 5 px
letters ("digraph" glyph, 6 px per letter), so a full 13-cell column holds 26 letters.

    python -X utf8 tools/font_en.py --selftest
    python -X utf8 tools/font_en.py --sheet OUT.png      every printable ASCII glyph, rotated back upright

Encoding: control sequences (|n |d %n %d %b %B %r) pass through as ASCII; every other run of text is split into
pairs of characters (an odd run gets a trailing space), and each distinct pair gets a 2-byte code b0 b1 with
b0 in 0x80-0x9F and b1 in 0x80-0xFF. The game's reader only treats '%' and '|' as control prefixes and reads every
other character as 2 bytes (0x08011E46 / 0x08012244), so these codes never collide with control or EUC text.
"""
