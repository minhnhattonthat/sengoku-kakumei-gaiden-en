W, H = 5, 9
FONT = {" ": ["....."] * H}
for _line in _ART.strip("\n").splitlines():
    _ch, *_rows = _line.split(" ")
    assert len(_rows) == H and all(len(r) == W for r in _rows), _line
    FONT[_ch] = _rows
PRINTABLE = "".join(chr(c) for c in range(0x20, 0x7F))
assert set(FONT) == set(PRINTABLE), set(PRINTABLE) ^ set(FONT)

# Typographic characters translators may type, folded to the font's ASCII.
FOLD = {"’": "'", "‘": "'", "“": '"', "”": '"', "—": "-", "–": "-", "…": "..."}

CONTROLS = re.compile(r"\|[nd]|%[nNdbBr]")
CELL = 12          # px per glyph cell along the column (the engine's advance)
LETTERS_PER_CELL = 2
GLYPH_ROWS = 13    # rows per font entry (16 bits each, at entry+6; the draw 0x08011C80 -> 0x080115EC reads from +6)
X_TOP = 10         # cell column that holds a letter's top row; row r of the letter goes to x = X_TOP - r
CODE_B0 = (0x80, 0xA0)   # first byte of an English pair code
MAX_PAIRS = (CODE_B0[1] - CODE_B0[0]) * 128


def fold(text):
    for a, b in FOLD.items():
        text = text.replace(a, b)
    return text


def tokens(text):
    """[(is_control, str)]: control sequences and the plain runs between them."""
    out, pos = [], 0
    for m in CONTROLS.finditer(text):
        if m.start() > pos:
            out.append((False, text[pos:m.start()]))
        out.append((True, m.group()))
        pos = m.end()
    if pos < len(text):
        out.append((False, text[pos:]))
    return out


def pairs(run):
    if len(run) % 2:
        run += " "
    return [run[i:i + 2] for i in range(0, len(run), 2)]


def cells(line):
    """Glyph cells one line (no |n inside) takes; %n/%d count as 0 here (runtime width)."""
    return sum(len(pairs(t)) for ctl, t in tokens(line) if not ctl)


def code(k):
    if not 0 <= k < MAX_PAIRS:
        raise ValueError(f"pair index {k} out of range ({MAX_PAIRS} codes)")
    return bytes((CODE_B0[0] + (k >> 7), 0x80 + (k & 0x7F)))


def glyph_rows(pair):
    """14 big-endian-ordered u16 rows (bit 15 = x 0) for a two-letter cell, letters rotated 90 degrees clockwise."""
    rows = [0] * GLYPH_ROWS
    for half, ch in enumerate(pair):
        art = FONT[ch]
        for r in range(H):          # letter row (top to bottom) -> cell x
            x = X_TOP - r
            for c in range(W):      # letter column (left to right) -> cell y
                if art[r][c] == "#":
                    rows[half * (W + 1) + c] |= 0x8000 >> x
    return rows


def glyph_bytes(pair):
    return b"".join(struct.pack(">H", v) for v in glyph_rows(pair))


class Encoder:
    """Pair dictionary over a set of English strings, deterministic for the same set. frozen: the pair list of the
    QA-toured build (data/text_pairs.json); its pairs keep their codes (unused ones too) and new pairs follow, so a
    text edit does not re-encode every other string."""

    def __init__(self, texts, frozen=None):
        seen = set()
        for t in texts:
            for ctl, run in tokens(fold(t)):
                if not ctl:
                    bad = set(run) - set(PRINTABLE)
                    if bad:
                        raise ValueError(f"no glyph for {''.join(sorted(bad))!r} in {t!r}")
                    seen.update(pairs(run))
        self.pairs = sorted(seen)
        if frozen:
            self.pairs = list(frozen) + sorted(seen - set(frozen))
        if len(self.pairs) > MAX_PAIRS:
            raise ValueError(f"{len(self.pairs)} distinct letter pairs, room for {MAX_PAIRS}")
        self.index = {p: k for k, p in enumerate(self.pairs)}

    def encode(self, text):
        out = bytearray()
        for ctl, run in tokens(fold(text)):
            if ctl:
                out += run.encode("ascii")
            else:
                for p in pairs(run):
                    out += code(self.index[p])
        return bytes(out)


def render_upright(text_line, scale=1):
    """Rows of a horizontal, upright rendering (for sheets/tests): list of strings of '#'/'.'."""
    rows = ["" for _ in range(H)]
    for ch in text_line:
        for r in range(H):
            rows[r] += FONT[ch][r] + "."
    return rows


def _selftest():
    for ch, art in FONT.items():
        assert all(len(r) == W for r in art), ch
    g = glyph_rows("MW")
    assert all(v & 0x3 == 0 for v in g), "ink spills into x 14-15"     # x <= 11 keeps 1 px to the next column
    assert g[5] == g[11] == g[12] == 0 and len(g) == GLYPH_ROWS
    # letter rows land on x 2..10, nothing outside the 12 px column
    for p in ["Mg", "jy", "|_"]:
        for v in glyph_rows(p):
            assert v & ~(((1 << 9) - 1) << (15 - X_TOP)) & 0xFFFF == 0, p
    e = Encoder(["Hello, %n!|nGo.", "Hi"])
    b = e.encode("Hello, %n!|nGo.")
    assert b"%n" in b and b"|n" in b and all(x >= 0x80 for x in b.replace(b"%n", b"").replace(b"|n", b""))
    assert len(b) == 2 * 4 + 2 + 2 + 2 + 2 * 2, b
    assert cells("Hello, %n!") == 5
    print(f"selftest ok: {len(FONT)} glyphs")


def _sheet(path):
    sys.path.insert(0, str(__import__("pathlib").Path(__file__).parent))
    import zlib
    lines = [PRINTABLE[:48], PRINTABLE[48:], "The quick brown fox jumps over the lazy dog."]
    img = []
    for ln in lines:
        img += render_upright(ln) + [""]
    w = max(len(r) for r in img)
    raw = b"".join(b"\0" + bytes(0 if c == "#" else 255 for c in r.ljust(w, ".")) for r in img)
    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, len(img), 8, 0, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")
    open(path, "wb").write(png)
    print(path)


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        _selftest()
    elif "--sheet" in sys.argv:
        _sheet(sys.argv[sys.argv.index("--sheet") + 1])
