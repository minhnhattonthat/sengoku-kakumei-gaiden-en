"""textmap.py: (re)generate data/text_sites.tsv, the list of every text pointer the build may rewrite.

A site is an aligned u32 0x08000000|target with the target inside one of textbank.RANGES and the site inside
the code (0x000000-0x04C3F4, literal pools) or the event/script tables (0x7303B8-0x759177). Sites found elsewhere
(sound data at 0x42xxxx-0x55xxxx, raw graphics) are coincidences: docs/re/text.md. Each target must start a
string (the byte before it is 0, or it is the first byte of its range). The build reads only the committed list: it never scans the ROM for pointers.

python -X utf8 tools/textmap.py [--check]   (--check: exit 1 if the committed list differs from a fresh scan)
"""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import textbank  # noqa: E402

SITE_REGIONS = [(0x000000, 0x04C3F4), (0x7303B8, 0x759178)]


def scan(rom):
    rows = []
    for lo, hi in SITE_REGIONS:
        for p in range(lo, hi, 4):
            t = struct.unpack_from("<I", rom, p)[0] - 0x08000000
            if textbank.bank_of(t) is not None:
                if rom[t - 1] != 0 and t not in {lo for _, lo, _ in textbank.RANGES}:
                    raise SystemExit(f"site {p:06x} -> {t:06x}: target does not start a string")
                rows.append((p, t))
    return rows


def render(rows):
    lines = ["# site\ttarget   (generated by tools/textmap.py; see docs/re/text.md)"]
    lines += [f"{p:06x}\t{t:06x}" for p, t in rows]
    return "\n".join(lines) + "\n"


def main():
    rom = textbank.original_rom()
    text = render(scan(rom))
    if "--check" in sys.argv:
        same = textbank.SITES.read_text(encoding="utf-8") == text
        print("text_sites.tsv", "matches" if same else "DIFFERS from a fresh scan")
        return 0 if same else 1
    textbank.SITES.parent.mkdir(exist_ok=True)
    textbank.SITES.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {textbank.SITES} ({text.count(chr(10)) - 1} sites)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
