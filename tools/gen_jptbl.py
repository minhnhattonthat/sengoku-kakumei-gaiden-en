"""gen_jptbl.py: write tbl/jp.tbl, the game's text table: EUC-JP (JIS X 0208) pairs, printable ASCII, 00={end}.

The control sequences (|n newline, %n name, %d number, %b %B %r) are plain ASCII in the ROM and stay as ASCII
text in the table, so decode -> encode is byte-exact. The debug menu's half-width katakana (JIS X 0201 bytes
A1-DF, 0x04E008..) decode as EUC pairs or [XX] escapes and still roundtrip; they are debug-only.
python -X utf8 tools/gen_jptbl.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def lines():
    out = ["# generated by tools/gen_jptbl.py: EUC-JP + ASCII; see docs/re/text.md", "00={end}", "20=\\s"]
    out += [f"{b:02X}={chr(b)}" for b in range(0x21, 0x7F)]
    seen = set(chr(b) for b in range(0x20, 0x7F))
    for b1 in range(0xA1, 0xFF):
        for b2 in range(0xA1, 0xFF):
            try:
                ch = bytes([b1, b2]).decode("euc_jp")
            except UnicodeDecodeError:
                continue
            if len(ch) != 1 or ch in seen or ch.encode("euc_jp") != bytes([b1, b2]):
                continue  # keep one code per character so encode(decode(x)) == x
            seen.add(ch)
            out.append(f"{b1:02X}{b2:02X}={ch}")
    return out


def main():
    path = ROOT / "tbl" / "jp.tbl"
    path.parent.mkdir(exist_ok=True)
    text = "\n".join(lines()) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
